// ============================================================
// Валидация доски (структура, уникальность, полнота)
// ============================================================

export interface BoardValidationError {
  code:
    | "EMPTY_TEXT"
    | "BAD_VALUE"
    | "DUP_ID"
    | "DUP_CAT_VALUE"
    | "NO_ANSWER"
    | "MISSING_CAT_VALUE"
    | "UNKNOWN_CAT"
    | "BAD_OPTIONS"
    | "OPT_LEAK";
  message: string;
}

const VALID_CATS = new Set(Object.keys(SVAYA_CATEGORIES) as SvoyaCategory[]);
const VALID_VALUES = new Set<number>(SVAYA_VALUES as unknown as number[]);

/**
 * Валидирует набор вопросов:
 * - все id уникальны
 * - cat ∈ SVAYA_CATEGORIES, value ∈ {500,1000,1500,2000,2500}
 * - round ∈ {0,1,2}
 * - q и explanation непустые
 * - answer ≥ 1 вариант, все непустые
 * - options ровно 4, все непустые, все уникальные
 * - options[0] содержит текст из answer (правильный вариант = правильный ответ)
 * - нет дублей (cat, value, round)
 * - для каждой категории и каждого номинала есть ВСЕ 3 раунда
 */
export function validateQuestions(
  questions: SvoyaQuestion[],
  requiredCats?: SvoyaCategory[]
): BoardValidationError[] {
  const errs: BoardValidationError[] = [];
  const seenIds = new Set<string>();
  const seenCatValRound = new Set<string>();
  const catValRoundCount: Record<string, Set<number>> = {};

  for (const q of questions) {
    const isPhoto = !!q.photoKind; // фото-вопросы (srs-photo-*) вне сетки (cat, value, round)

    // id
    if (!q.id || !q.id.trim()) {
      errs.push({ code: "EMPTY_TEXT", message: "Пустой id" });
      continue;
    }
    if (seenIds.has(q.id)) {
      errs.push({ code: "DUP_ID", message: `Дубликат id: ${q.id}` });
    }
    seenIds.add(q.id);

    // cat
    if (!VALID_CATS.has(q.cat)) {
      errs.push({ code: "UNKNOWN_CAT", message: `Неизвестная категория: ${q.cat}` });
      continue;
    }

    // value
    if (!VALID_VALUES.has(q.value)) {
      errs.push({ code: "BAD_VALUE", message: `Некорректный номинал ${q.value} (${q.id})` });
      continue;
    }

    // round
    if (q.round !== 0 && q.round !== 1 && q.round !== 2) {
      errs.push({ code: "BAD_VALUE", message: `Некорректный раунд ${q.round} (${q.id})` });
      continue;
    }

    // q text
    if (!q.q || q.q.trim().length < 3) {
      errs.push({ code: "EMPTY_TEXT", message: `Слишком короткий вопрос: ${q.id}` });
    }

    // explanation
    if (!q.explanation || q.explanation.trim().length < 3) {
      errs.push({ code: "EMPTY_TEXT", message: `Пустое пояснение: ${q.id}` });
    }

    // answer
    if (!q.answer || q.answer.length === 0) {
      errs.push({ code: "NO_ANSWER", message: `Нет ответа: ${q.id}` });
    } else {
      for (const a of q.answer) {
        if (!a || !a.trim()) {
          errs.push({ code: "EMPTY_TEXT", message: `Пустой вариант ответа: ${q.id}` });
        }
      }
    }

    // options: ровно 4, все непустые, все уникальные
    if (!q.options || q.options.length !== 4) {
      errs.push({ code: "BAD_OPTIONS", message: `Нужно ровно 4 варианта: ${q.id} (сейчас ${q.options?.length})` });
    } else {
      const normOpts = q.options.map((o) => o.trim().toLowerCase());
      for (let i = 0; i < 4; i++) {
        if (!q.options[i] || !q.options[i].trim()) {
          errs.push({ code: "EMPTY_TEXT", message: `Пустой вариант [${i}]: ${q.id}` });
        }
      }
      if (new Set(normOpts).size < 4) {
        errs.push({ code: "BAD_OPTIONS", message: `Дубликаты в вариантах: ${q.id}` });
      }
      // options[0] (правильный) должен содержать или совпадать с answer[0]
      const correctOpt = normOpts[0] ?? "";
      const firstAnswer = (q.answer[0] ?? "").trim().toLowerCase();
      if (firstAnswer && !correctOpt.includes(firstAnswer) && !firstAnswer.includes(correctOpt)) {
        errs.push({ code: "OPT_LEAK", message: `options[0] не совпадает с answer[0]: ${q.id}` });
      }
    }

    // (cat, value, round) unique — только для текстовых вопросов (фото вне сетки)
    if (!isPhoto) {
      const key = `${q.cat}:${q.value}:${q.round}`;
      if (seenCatValRound.has(key)) {
        errs.push({ code: "DUP_CAT_VALUE", message: `Дубль: ${q.cat} ${q.value} r${q.round} (${q.id})` });
      }
      seenCatValRound.add(key);

      // cat → values → rounds coverage
      if (!catValRoundCount[q.cat]) catValRoundCount[q.cat] = new Set();
      catValRoundCount[q.cat].add(q.value * 10 + q.round);
    }
  }

  // Покрытие: каждая требуемая категория имеет все 5 номиналов × 3 раунда
  const cats = requiredCats ?? (Object.keys(SVAYA_CATEGORIES) as SvoyaCategory[]);
  for (const cat of cats) {
    const have = catValRoundCount[cat] ?? new Set<number>();
    for (const v of SVAYA_VALUES) {
      for (const r of SVAYA_ROUNDS) {
        if (!have.has(v * 10 + r)) {
          errs.push({
            code: "MISSING_CAT_VALUE",
            message: `Нет вопроса: ${cat} ${v} r${r}`,
          });
        }
      }
    }
  }

  return errs;
}

/** Быстрая проверка: все ли вопросы валидны (0 ошибок). */
export function isQuestionsValid(
  questions: SvoyaQuestion[],
  requiredCats?: SvoyaCategory[]
): boolean {
  return validateQuestions(questions, requiredCats).length === 0;
}
