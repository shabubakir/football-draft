// ============================================================
// СВОЯ ИГРА — банк вопросов (Jeopardy)
// ============================================================
// 9 категорий × 5 номиналов (500/1000/1500/2000/2500) × 3 раунда
// = 135 текстовых + 15 фото-вопросов (серии, эмодзи-фолбэк) = 150.
//
// ID-схема:
//   Текст:  <catPrefix>-<value>-r<round>     напр. "fb-500-r0"
//   Фото:   srs-photo-<idx>                  напр. "srs-photo-0"
//
// round: 0 | 1 | 2. При создании доски движок детерминированно
// выбирает раунд для каждой ячейки по seed комнаты
// (roundForCell), затем подставляет qId. Старые qId вида
// "fb-500" (без -rN) поддерживаются fallback-поиском.
//
// options: string[] — ровно 4 варианта ответа.
//   options[0] — ВСЕГДА правильный ответ (движок определяет вердикт
//   по индексу, сервер никогда не доверяет клиенту).
//   options[1..3] — неправильные варианты (дистракторы).
// answer: string[] — допустимые формулировки правильного ответа.
// explanation — показывается на REVEAL.
// imgUrl — URL изображения (только у фото-вопросов, опционально).
//   Если не задан или не загрузился — UI показывает эмодзи-фолбэк.
//
// Факты сверены где возможно; спорные помечены "REVIEW".
// ============================================================

export type SvoyaCategory =
  | "football"
  | "cs2"
  | "movies"
  | "series"
  | "music"
  | "geo"
  | "history"
  | "kazakhstan"
  | "mixed";

export const SVAYA_CATEGORIES: Record<SvoyaCategory, string> = {
  football: "Футбол",
  cs2: "CS2 и игры",
  movies: "Кино",
  series: "Сериалы",
  music: "Музыка",
  geo: "География",
  history: "История",
  kazakhstan: "Казахстан",
  mixed: "Смешанное",
};

export const SVAYA_VALUES = [500, 1000, 1500, 2000, 2500] as const;
export type SvoyaValue = (typeof SVAYA_VALUES)[number];

export type SvoyaRound = 0 | 1 | 2;
export const SVAYA_ROUNDS: SvoyaRound[] = [0, 1, 2];

export interface SvoyaQuestion {
  id: string;
  cat: SvoyaCategory;
  value: SvoyaValue;
  /** Раунд (0..2) — один из 3 вопросов с одинаковым номиналом. */
  round: SvoyaRound;
  q: string;
  /** Ровно 4 варианта. options[0] — правильный (для движка). */
  options: string[];
  /** Допустимые формулировки правильного ответа (для валидации). */
  answer: string[];
  /** Пояснение для REVEAL. */
  explanation: string;
  /**
   * URL изображения (опционально, только у фото-вопросов).
   * Если не задан или не загрузился — UI показывает эмодзи-фолбэк.
   * ВАЖНО: не подставляем вымышленные URL — только проверенные.
   */
  imgUrl?: string;
  /** Эмодзи-фолбэк (показывается, если imgUrl не задан или не загрузился). */
  emoji?: string;
  /** Тип фото-вопроса (для легенды в UI): "show" | "character". */
  photoKind?: "show" | "character";
}

const Q = (
  id: string,
  cat: SvoyaCategory,
  value: SvoyaValue,
  round: SvoyaRound,
  q: string,
  options: string[],
  answer: string[],
  explanation: string,
  extra?: { imgUrl?: string; emoji?: string; photoKind?: "show" | "character" }
): SvoyaQuestion => ({ id, cat, value, round, q, options, answer, explanation, ...extra });

