/** Все вопросы (полные данные — только для движка/валидации). */
export const SVAYA_QUESTIONS: SvoyaQuestion[] = [
  ...football, ...cs2, ...movies, ...music,
  ...geo, ...history, ...kazakhstan, ...mixed,
];

/** Публичный просмотр вопроса (без answer) — для UI до REVEAL. */
export type PublicQuestion = Omit<SvoyaQuestion, "answer">;

/** Возвращает публичную версию вопроса (без ответ). */
export function toPublicQuestion(q: SvoyaQuestion): PublicQuestion {
  const { answer: _a, ...pub } = q;
  return pub;
}

/** Ищет вопрос по id. */
export function findQuestion(id: string): SvoyaQuestion | undefined {
  return SVAYA_QUESTIONS.find((q) => q.id === id);
}

// ============================================================
// Валидация доски (структура, уникальность, полнота)
// ============================================================

export interface BoardValidationError {
  code:
    | "EMPTY_TEXT"
    | "BAD_VALUE"
    | "DUP_ID"
    | "DUP_CAT_VALUE"
    | "NO_ANSWER"
    | "MISSING_CAT_VALUE"
    | "UNKNOWN_CAT";
  message: string;
}

const VALID_CATS = new Set(Object.keys(SVAYA_CATEGORIES) as SvoyaCategory[]);
const VALID_VALUES = new Set<number>(SVAYA_VALUES as unknown as number[]);

/**
 * Валидирует набор вопросов:
 * - все id уникальны
 * - cat ∈ SVAYA_CATEGORIES, value ∈ {100,200,300,400,500}
 * - q и explanation непустые
 * - answer ≥ 1 вариант, все непустые
 * - нет дублей (cat, value)
 * - для каждой категории есть все 5 номиналов
 */
export function validateQuestions(
  questions: SvoyaQuestion[],
  requiredCats?: SvoyaCategory[]
): BoardValidationError[] {
  const errs: BoardValidationError[] = [];
  const seenIds = new Set<string>();
  const seenCatVal = new Set<string>();
  const catValCount: Record<string, Set<number>> = {};

  for (const q of questions) {
    // id
    if (!q.id || !q.id.trim()) {
      errs.push({ code: "EMPTY_TEXT", message: "Пустой id" });
      continue;
    }
    if (seenIds.has(q.id)) {
      errs.push({ code: "DUP_ID", message: `Дубликат id: ${q.id}` });
    }
    seenIds.add(q.id);

    // cat
    if (!VALID_CATS.has(q.cat)) {
      errs.push({ code: "UNKNOWN_CAT", message: `Неизвестная категория: ${q.cat}` });
      continue;
    }

    // value
    if (!VALID_VALUES.has(q.value)) {
      errs.push({ code: "BAD_VALUE", message: `Некорректный номинал ${q.value} (${q.id})` });
      continue;
    }

    // q text
    if (!q.q || q.q.trim().length < 3) {
      errs.push({ code: "EMPTY_TEXT", message: `Слишком короткий вопрос: ${q.id}` });
    }

    // explanation
    if (!q.explanation || q.explanation.trim().length < 3) {
      errs.push({ code: "EMPTY_TEXT", message: `Пустое пояснение: ${q.id}` });
    }

    // answer
    if (!q.answer || q.answer.length === 0) {
      errs.push({ code: "NO_ANSWER", message: `Нет ответа: ${q.id}` });
    } else {
      for (const a of q.answer) {
        if (!a || !a.trim()) {
          errs.push({ code: "EMPTY_TEXT", message: `Пустой вариант ответа: ${q.id}` });
        }
      }
    }

    // (cat, value) unique
    const key = `${q.cat}:${q.value}`;
    if (seenCatVal.has(key)) {
      errs.push({ code: "DUP_CAT_VALUE", message: `Дубль: ${q.cat} ${q.value} (${q.id})` });
    }
    seenCatVal.add(key);

    // cat → values coverage
    if (!catValCount[q.cat]) catValCount[q.cat] = new Set();
    catValCount[q.cat].add(q.value);
  }

  // Покрытие: каждая требуемая категория имеет все 5 номиналов
  const cats = requiredCats ?? (Object.keys(SVAYA_CATEGORIES) as SvoyaCategory[]);
  for (const cat of cats) {
    const have = catValCount[cat] ?? new Set<number>();
    for (const v of SVAYA_VALUES) {
      if (!have.has(v)) {
        errs.push({
          code: "MISSING_CAT_VALUE",
          message: `Нет вопроса: ${cat} ${v}`,
        });
      }
    }
  }

  return errs;
}

/** Быстрая проверка: все ли вопросы валидны (0 ошибок). */
export function isQuestionsValid(
  questions: SvoyaQuestion[],
  requiredCats?: SvoyaCategory[]
): boolean {
  return validateQuestions(questions, requiredCats).length === 0;
}
