//   25 вопросов = 5 категорий × 5 номиналов (полная доска).
//   15 вопросов = 3 категории × 5 номиналов (выбор случайных 3 из 5).
//
// options: string[] — ровно 4 варианта ответа.
//   options[0] — ВСЕГДА правильный ответ (движок определяет вердикт
