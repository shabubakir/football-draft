// Категории: football, cs2, movies, music, geo, history, kazakhstan, mixed
// У каждой категории — 5 вопросов (номиналы 100/200/300/400/500).
// Доска 5×5 = 5 категорий × 5 номиналов = 25 ячеек.
//
// answer: string[] — допустимые формулировки правильного ответа
// (для автоматического вердикта, если хост не ответил вовремя).
// explanation — показывается на REVEAL.
//
// Факты сверены где возможно; спорные/обновляемые помечены "REVIEW"
// в комментарии — их нужно проверить вручную перед запуском.
// ============================================================

export type SvoyaCategory =
  | "football"
  | "cs2"
  | "movies"
  | "music"
  | "geo"
  | "history"
  | "kazakhstan"
  | "mixed";

export const SVAYA_CATEGORIES: Record<SvoyaCategory, string> = {
  football: "Футбол",
  cs2: "CS2 и игры",
  movies: "Кино",
  music: "Музыка",
  geo: "География",
  history: "История",
  kazakhstan: "Казахстан",
  mixed: "Смешанное",
};

export const SVAYA_VALUES = [100, 200, 300, 400, 500] as const;
export type SvoyaValue = (typeof SVAYA_VALUES)[number];

export interface SvoyaQuestion {
  id: string;
  cat: SvoyaCategory;
  value: SvoyaValue;
  q: string;
  /** Допустимые формулировки правильного ответа (нормализуются). */
  answer: string[];
  /** Пояснение для REVEAL. */
  explanation: string;
}

const Q = (
  id: string,
  cat: SvoyaCategory,
  value: SvoyaValue,
  q: string,
  answer: string[],
  explanation: string
): SvoyaQuestion => ({ id, cat, value, q, answer, explanation });

